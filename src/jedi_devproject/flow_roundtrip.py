"""Flow Designer round-trip verification harness (roadmap item 4.2.4).

Deterministic, instance-facing verification flow for the narrow Flow builder:

1. Retrieve the current flow graph state from the DEV instance (the same
   ``sys_hub_*`` discovery surfaces the read-only context worker uses) and
   fail closed if it no longer matches the diff intent's
   ``existing_graph_hash``.
2. Build customer updates with the deterministic builder (``flow_builder``),
   which itself enforces the evidence-driven readiness contract.
3. Import them as a loaded Retrieved Update Set, reusing the existing
   ``update_set_handoff.import_retrieved_update_set`` plumbing. The harness
   NEVER previews or commits the update set: ServiceNow-native preview/commit
   stays the human review boundary (``committed_by_harness`` is always
   false).
4. Re-retrieve the flow graph and assert it equals the intended post-diff
   graph: the new action and edge splice are present where specified (or the
   one condition changed), every untouched node is byte-stable, the node
   count matches the diff, and the flow snapshot was regenerated by the
   platform (``flow-snapshot-update-strategy-v1`` snapshot regeneration
   evidence; the builder never hand-mutates snapshots).

Because the harness never commits, the post-import graph assertions are
expected to pass after a human previews and commits the produced update set;
running the harness before commit yields a typed failing report that records
exactly which assertions are still pending. The ``FlowRoundTripReport`` is
suitable for UAT evidence and for the builder-maturity evidence loop.
"""

from __future__ import annotations

import hashlib
import json
import re
from typing import Any, Literal, Protocol, cast

from pydantic import BaseModel, ConfigDict

from jedi_devproject.discovery.fetch import _display_or_value, _reference_value
from jedi_devproject.flow_builder import (
    FlowBuilderNodeTable,
    FlowCustomerUpdateBuildResult,
    FlowGeneratedCustomerUpdate,
    FlowRetrievedNodeEvidence,
    build_flow_customer_updates,
    stable_flow_sys_id,
)
from jedi_devproject.flow_designer_generation import (
    FlowGraphDiffIntent,
    FlowGraphDiffOperation,
)
from jedi_devproject.flow_xml_evidence import FlowXmlEvidenceBundle
from jedi_devproject.update_set_handoff import import_retrieved_update_set

FLOW_ROUNDTRIP_REPORT_VERSION: Literal["flow-roundtrip-report-v1"] = "flow-roundtrip-report-v1"

_SYS_ID_PATTERN = r"[a-f0-9]{32}"
_FLOW_RECORD_FIELDS = ["sys_id", "name", "active", "status", "latest_snapshot"]
_NODE_FIELDS_BY_TABLE: dict[str, list[str]] = {
    "sys_hub_action_instance": [
        "sys_id",
        "flow",
        "order",
        "action_type",
        "display_text",
        "connected_to",
    ],
    "sys_hub_flow_logic_instance_v2": [
        "sys_id",
        "flow",
        "order",
        "logic_definition",
        "display_text",
        "connected_to",
        "condition",
    ],
}
_REFERENCE_NODE_FIELDS = {"sys_id", "flow", "connected_to"}


class FlowRoundTripClient(Protocol):
    def fetch_table_records(
        self,
        *,
        table: str,
        lookup: dict[str, str],
        fields: list[str] | None = None,
        limit: int = 100,
    ) -> list[dict[str, Any]]: ...

    def import_update_set_xml(
        self,
        *,
        service_id: str,
        update_set_xml: str,
    ) -> dict[str, Any]: ...


class FlowGraphNodeState(BaseModel):
    model_config = ConfigDict(extra="forbid")

    table: str
    sys_id: str
    fields: dict[str, str]

    def canonical(self) -> str:
        return json.dumps({"table": self.table, **self.fields}, sort_keys=True)


class FlowGraphState(BaseModel):
    model_config = ConfigDict(extra="forbid")

    flow_name: str
    flow_sys_id: str
    latest_snapshot: str
    nodes: dict[str, FlowGraphNodeState]
    graph_hash: str


class FlowRoundTripAssertion(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: str
    passed: bool
    detail: str = ""


class FlowRoundTripReport(BaseModel):
    model_config = ConfigDict(extra="forbid")

    version: Literal["flow-roundtrip-report-v1"]
    flow_name: str
    flow_sys_id: str
    operation: FlowGraphDiffOperation
    update_set_name: str
    update_set_remote_sys_id: str
    update_set_sys_id: str = ""
    customer_update_names: list[str]
    graph_hash_before: str
    graph_hash_after: str = ""
    snapshot_before: str = ""
    snapshot_after: str = ""
    review_boundary: Literal["retrieved_update_set_preview_commit"]
    committed_by_harness: Literal[False]
    assertions: list[FlowRoundTripAssertion]
    passed: bool


def retrieve_flow_graph_state(
    *,
    client: FlowRoundTripClient,
    flow_name: str,
) -> FlowGraphState:
    """Retrieve the current action/logic graph state for one named flow."""
    cleaned_flow_name = flow_name.strip()
    if cleaned_flow_name == "":
        raise ValueError("Flow round-trip requires a flow name")
    flow_records = client.fetch_table_records(
        table="sys_hub_flow",
        lookup={"name": cleaned_flow_name},
        fields=list(_FLOW_RECORD_FIELDS),
        limit=2,
    )
    if not flow_records:
        raise ValueError(f"Flow round-trip flow not found: {cleaned_flow_name}")
    if len(flow_records) > 1:
        raise ValueError(f"Flow round-trip requires exactly one flow match: {cleaned_flow_name}")
    flow_record = flow_records[0]
    flow_sys_id = _reference_value(flow_record.get("sys_id")).strip().lower()
    if not re.fullmatch(_SYS_ID_PATTERN, flow_sys_id):
        raise ValueError("Flow round-trip flow sys_id must be 32 hex characters")
    nodes: dict[str, FlowGraphNodeState] = {}
    for table, field_names in _NODE_FIELDS_BY_TABLE.items():
        records = client.fetch_table_records(
            table=table,
            lookup={"flow": flow_sys_id},
            fields=list(field_names),
            limit=200,
        )
        for record in records:
            node = _node_state(table=table, field_names=field_names, record=record)
            if node.sys_id in nodes:
                raise ValueError(f"Flow round-trip retrieved ambiguous node: {node.sys_id}")
            nodes[node.sys_id] = node
    return FlowGraphState(
        flow_name=cleaned_flow_name,
        flow_sys_id=flow_sys_id,
        latest_snapshot=_reference_value(flow_record.get("latest_snapshot")).strip().lower(),
        nodes=nodes,
        graph_hash=flow_graph_state_hash(nodes),
    )


def flow_graph_state_hash(nodes: dict[str, FlowGraphNodeState]) -> str:
    """Stable content hash over the canonical node states."""
    canonical = "\n".join(nodes[sys_id].canonical() for sys_id in sorted(nodes))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def run_flow_roundtrip(
    *,
    client: FlowRoundTripClient,
    intent: FlowGraphDiffIntent,
    evidence_bundle: FlowXmlEvidenceBundle,
) -> FlowRoundTripReport:
    """Public entrypoint: build, import, re-retrieve, and verify one flow diff.

    Suitable for later CLI wiring. Builder contract violations (stale
    evidence, forbidden operations, readiness gaps) raise immediately;
    instance-facing verification outcomes (import failures, graph
    mismatches, node count drift, missing snapshot regeneration) are
    recorded as failed assertions in the typed report.
    """
    pre_state = retrieve_flow_graph_state(client=client, flow_name=intent.flow_name)
    intent_hash = intent.existing_graph_hash.strip().lower()
    assertions: list[FlowRoundTripAssertion] = []
    if pre_state.graph_hash != intent_hash:
        assertions.append(
            FlowRoundTripAssertion(
                name="pre_import_graph_current",
                passed=False,
                detail=(
                    "retrieved graph hash does not match Flow graph diff: "
                    f"retrieved {pre_state.graph_hash}, intent {intent_hash}"
                ),
            )
        )
        return _report(
            intent=intent,
            operation=intent.requested_graph_diff[0].operation,
            pre_state=pre_state,
            update_set_name=_update_set_name(intent.flow_name),
            remote_sys_id="",
            customer_update_names=[],
            assertions=assertions,
        )
    assertions.append(FlowRoundTripAssertion(name="pre_import_graph_current", passed=True))
    build_result = build_flow_customer_updates(
        intent=intent,
        evidence_bundle=evidence_bundle,
        retrieved_nodes=_retrieved_node_evidence(pre_state),
    )
    update_set_name = _update_set_name(intent.flow_name)
    remote_sys_id = stable_flow_sys_id(
        "flow-roundtrip", pre_state.flow_sys_id, pre_state.graph_hash, build_result.operation
    )
    try:
        update_set_sys_id = import_retrieved_update_set(
            client=client,
            update_set_name=update_set_name,
            remote_sys_id=remote_sys_id,
            description=_update_set_description(build_result),
            customer_updates=[
                update.handoff_record() for update in build_result.customer_updates
            ],
        )
    except Exception as exc:
        assertions.append(
            FlowRoundTripAssertion(
                name="retrieved_update_set_imported",
                passed=False,
                detail=str(exc),
            )
        )
        return _report(
            intent=intent,
            operation=build_result.operation,
            pre_state=pre_state,
            update_set_name=update_set_name,
            remote_sys_id=remote_sys_id,
            customer_update_names=[update.name for update in build_result.customer_updates],
            assertions=assertions,
        )
    assertions.append(
        FlowRoundTripAssertion(name="retrieved_update_set_imported", passed=True)
    )
    post_state = retrieve_flow_graph_state(client=client, flow_name=intent.flow_name)
    assertions.extend(
        _post_import_assertions(
            pre_state=pre_state,
            post_state=post_state,
            build_result=build_result,
        )
    )
    return _report(
        intent=intent,
        operation=build_result.operation,
        pre_state=pre_state,
        post_state=post_state,
        update_set_name=update_set_name,
        remote_sys_id=remote_sys_id,
        update_set_sys_id=update_set_sys_id,
        customer_update_names=[update.name for update in build_result.customer_updates],
        assertions=assertions,
    )


def _post_import_assertions(
    *,
    pre_state: FlowGraphState,
    post_state: FlowGraphState,
    build_result: FlowCustomerUpdateBuildResult,
) -> list[FlowRoundTripAssertion]:
    assertions: list[FlowRoundTripAssertion] = []
    expected_nodes = {
        update.record_sys_id: _expected_node_state(update)
        for update in build_result.customer_updates
    }
    for sys_id in sorted(expected_nodes):
        expected = expected_nodes[sys_id]
        actual = post_state.nodes.get(sys_id)
        if actual is None:
            assertions.append(
                FlowRoundTripAssertion(
                    name=f"graph_matches_intent:{expected.table}:{sys_id}",
                    passed=False,
                    detail="expected node was not retrieved after import",
                )
            )
        else:
            matches = actual.canonical() == expected.canonical()
            assertions.append(
                FlowRoundTripAssertion(
                    name=f"graph_matches_intent:{expected.table}:{sys_id}",
                    passed=matches,
                    detail=(
                        ""
                        if matches
                        else f"expected {expected.canonical()}, retrieved {actual.canonical()}"
                    ),
                )
            )
    drifted = sorted(
        sys_id
        for sys_id, node in pre_state.nodes.items()
        if sys_id not in expected_nodes
        and (
            post_state.nodes.get(sys_id) is None
            or post_state.nodes[sys_id].canonical() != node.canonical()
        )
    )
    assertions.append(
        FlowRoundTripAssertion(
            name="unchanged_nodes_byte_stable",
            passed=not drifted,
            detail=", ".join(drifted),
        )
    )
    expected_count = len(pre_state.nodes) + (
        2 if build_result.operation == "add_action" else 0
    )
    assertions.append(
        FlowRoundTripAssertion(
            name="node_count_matches_diff",
            passed=len(post_state.nodes) == expected_count,
            detail=f"expected {expected_count}, retrieved {len(post_state.nodes)}",
        )
    )
    snapshot_regenerated = bool(
        re.fullmatch(_SYS_ID_PATTERN, post_state.latest_snapshot)
    ) and post_state.latest_snapshot != pre_state.latest_snapshot
    assertions.append(
        FlowRoundTripAssertion(
            name="flow_snapshot_regenerated",
            passed=snapshot_regenerated,
            detail=(
                ""
                if snapshot_regenerated
                else (
                    f"latest_snapshot before {pre_state.latest_snapshot or '(empty)'}, "
                    f"after {post_state.latest_snapshot or '(empty)'}"
                )
            ),
        )
    )
    return assertions


def _expected_node_state(update: FlowGeneratedCustomerUpdate) -> FlowGraphNodeState:
    field_names = _NODE_FIELDS_BY_TABLE[update.table]
    return FlowGraphNodeState(
        table=update.table,
        sys_id=update.record_sys_id,
        fields={name: update.fields.get(name, "") for name in field_names},
    )


def _retrieved_node_evidence(state: FlowGraphState) -> list[FlowRetrievedNodeEvidence]:
    return [
        FlowRetrievedNodeEvidence(
            table=cast(FlowBuilderNodeTable, node.table),
            sys_id=node.sys_id,
            display_text=node.fields.get("display_text", ""),
            order=int(node.fields.get("order") or "0"),
            action_type=node.fields.get("action_type", ""),
            logic_definition=node.fields.get("logic_definition", ""),
            connected_to=node.fields.get("connected_to", ""),
            condition=node.fields.get("condition", ""),
        )
        for _, node in sorted(state.nodes.items())
    ]


def _node_state(
    *,
    table: str,
    field_names: list[str],
    record: dict[str, Any],
) -> FlowGraphNodeState:
    fields: dict[str, str] = {}
    for name in field_names:
        if name in _REFERENCE_NODE_FIELDS:
            fields[name] = _reference_value(record.get(name)).strip().lower()
        elif name == "order":
            order_text = _display_or_value(record.get(name)).strip()
            fields[name] = order_text if order_text.isdigit() else "0"
        else:
            fields[name] = _display_or_value(record.get(name))
    sys_id = fields["sys_id"]
    if not re.fullmatch(_SYS_ID_PATTERN, sys_id):
        raise ValueError(f"Flow round-trip node sys_id must be 32 hex characters: {table}")
    return FlowGraphNodeState(table=table, sys_id=sys_id, fields=fields)


def _update_set_name(flow_name: str) -> str:
    return f"JEDI Flow Round-Trip - {flow_name}"


def _update_set_description(build_result: FlowCustomerUpdateBuildResult) -> str:
    lines = [
        f"Jedi DevProject Flow Designer round-trip verification for {build_result.flow_name}.",
        "",
        f"Builder: {build_result.builder_version}",
        f"Operation: {build_result.operation}",
        f"Graph hash: {build_result.graph_hash}",
        "Customer updates:",
        *(f"- {update.name}" for update in build_result.customer_updates),
        "",
        (
            "This retrieved Update Set is round-trip verification evidence. Preview, "
            "scan, and commit only after ServiceNow-native review; the harness never "
            "commits."
        ),
    ]
    return "\n".join(lines)


def _report(
    *,
    intent: FlowGraphDiffIntent,
    operation: FlowGraphDiffOperation,
    pre_state: FlowGraphState,
    update_set_name: str,
    remote_sys_id: str,
    customer_update_names: list[str],
    assertions: list[FlowRoundTripAssertion],
    post_state: FlowGraphState | None = None,
    update_set_sys_id: str = "",
) -> FlowRoundTripReport:
    return FlowRoundTripReport(
        version=FLOW_ROUNDTRIP_REPORT_VERSION,
        flow_name=intent.flow_name,
        flow_sys_id=pre_state.flow_sys_id,
        operation=operation,
        update_set_name=update_set_name,
        update_set_remote_sys_id=remote_sys_id,
        update_set_sys_id=update_set_sys_id,
        customer_update_names=customer_update_names,
        graph_hash_before=pre_state.graph_hash,
        graph_hash_after=post_state.graph_hash if post_state is not None else "",
        snapshot_before=pre_state.latest_snapshot,
        snapshot_after=post_state.latest_snapshot if post_state is not None else "",
        review_boundary="retrieved_update_set_preview_commit",
        committed_by_harness=False,
        assertions=assertions,
        passed=all(assertion.passed for assertion in assertions),
    )
